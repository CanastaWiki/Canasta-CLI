def parse_heap(value):
    """A heap setting such as 512m or 2g in megabytes, or None if invalid."""
    match = _HEAP.match((value or "").strip())
    if not match:
        return None
    size = int(match.group(1))
    return size * 1024 if match.group(2) in "gG" else size


def heap_mb(values):
    """The heap the cluster runs with: the largest of its instances' valid
    settings, or the default when none sets one."""
    sizes = [s for s in (parse_heap(v) for v in values) if s]
    return max(sizes) if sizes else DEFAULT_HEAP_MB


