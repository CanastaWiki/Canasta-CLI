#!/usr/bin/python
# -*- coding: utf-8 -*-

"""Ansible module: start a Compose instance at boot under rootless Podman.

Podman has no daemon to restore containers at boot, so their restart
policies do nothing after a reboot. A systemd user unit per instance,
canasta-<id>.service, runs the instance's `compose up -d` at boot instead,
as the canasta-edge units do for the edge. It runs the compose command
directly, as the edge's units run podman, so it needs no canasta install
or registry on the host.
"""

from __future__ import absolute_import, division, print_function
__metaclass__ = type

DOCUMENTATION = r"""
---
module: canasta_boot_unit
short_description: Manage a Compose instance's boot unit under rootless Podman
description:
  - Under rootless Podman, writes and enables the systemd user unit
    canasta-<id>.service, which brings the instance up at boot. Does nothing
    under Docker, whose daemon restores containers itself.
options:
  state:
    description: >-
      enabled writes the unit from the instance's current compose layers and
      profiles and enables it. disabled disables it, so a stopped instance
      stays stopped across a reboot. absent disables and removes it.
    type: str
    choices: [enabled, disabled, absent]
    default: enabled
  instance_id:
    type: str
    required: true
  instance_path:
    description: Required with state=enabled.
    type: str
  compose_command:
    type: str
    default: docker compose
  inspect_command:
    type: str
    default: docker
  devmode:
    type: bool
    default: false
"""

import os
import shlex
import shutil
import tempfile

from ansible.module_utils.basic import AnsibleModule
from ansible.module_utils.canasta_env_keys import modernize_values

# Layer order matches the compose file arguments of
# roles/orchestrator/tasks/start.yml.
LAYERS = ("docker-compose.sidecars.yml", "docker-compose.web-env.yml",
          "docker-compose.edge.yml", "docker-compose.override.yml")
DEV_LAYER = "docker-compose.dev.yml"
EDGE_UNIT = "canasta-edge.service"

UNIT_TEXT = """\
# Generated by Canasta. Do not edit.
[Unit]
Description=Canasta instance '%(id)s'
After=%(edge)s

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=%(path)s
Environment=%(env)s
ExecStart=%(exec)s
TimeoutStartSec=900

[Install]
WantedBy=default.target
"""


def unit_name(instance_id):
    return "canasta-%s.service" % instance_id


def units_dir():
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return os.path.join(base, "systemd", "user")


def uses_units(inspect):
    """Rootless Podman, the only Podman setup the CLI supports."""
    return "podman" in os.path.basename(inspect or "")


def _user_env():
    runtime = os.environ.get("XDG_RUNTIME_DIR") or "/run/user/%d" % os.getuid()
    return {"XDG_RUNTIME_DIR": runtime,
            "DBUS_SESSION_BUS_ADDRESS": "unix:path=%s/bus" % runtime}


def systemctl(run, *args):
    return run(["systemctl", "--user"] + list(args), env=_user_env())


def _read(path):
    try:
        with open(path) as handle:
            return handle.read()
    except (IOError, OSError):
        return None


def _write_if_changed(path, content):
    if _read(path) == content:
        return False
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".tmp-")
    with os.fdopen(fd, "w") as handle:
        handle.write(content)
    os.chmod(tmp, 0o644)
    os.rename(tmp, path)
    return True


def read_profiles(instance_path):
    """COMPOSE_PROFILES from the instance's .env, which podman-compose
    does not read itself."""
    env = {}
    for line in (_read(os.path.join(instance_path, ".env")) or "").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        env[key.strip()] = value
    raw = modernize_values(env).get("COMPOSE_PROFILES", "")
    return [p.strip() for p in raw.split(",") if p.strip()]


def compose_argv(compose_command, instance_path, devmode=False):
    """The `up -d` the instance's start runs, with the compose command's
    executable resolved: the user manager's PATH is not the operator's."""
    argv = shlex.split(compose_command)
    argv[0] = shutil.which(argv[0]) or argv[0]
    argv += ["-f", "docker-compose.yml"]
    for layer in LAYERS:
        if os.path.exists(os.path.join(instance_path, layer)):
            argv += ["-f", layer]
    if devmode:
        argv += ["-f", DEV_LAYER]
    for profile in read_profiles(instance_path):
        argv += ["--profile", profile]
    return argv + ["up", "-d"]


def _quote(arg):
    """One ExecStart word: systemd expands % specifiers and $ variables."""
    arg = arg.replace("%", "%%").replace("$", "$$")
    if arg and not any(c in arg for c in " \t\"'\\;"):
        return arg
    return '"%s"' % arg.replace("\\", "\\\\").replace('"', '\\"')


def render(instance_id, instance_path, argv, path_env):
    return UNIT_TEXT % {
        "id": instance_id, "edge": EDGE_UNIT, "path": _quote(instance_path),
        "env": _quote("PATH=%s" % path_env),
        "exec": " ".join(_quote(a) for a in argv)}


def enable(run, instance_id, instance_path, compose_command, devmode=False):
    """Write and enable the unit. Returns (changed, warning)."""
    if systemctl(run, "show-environment")[0] != 0:
        return False, (
            "Instance '%s' will not start again after a reboot: the operator's "
            "systemd user manager does not answer. Enable lingering for this user "
            "('canasta install podman' does)." % instance_id)
    directory = units_dir()
    os.makedirs(directory, exist_ok=True)
    unit = unit_name(instance_id)
    text = render(instance_id, instance_path,
                  compose_argv(compose_command, instance_path, devmode),
                  os.environ.get("PATH", "/usr/local/bin:/usr/bin:/bin"))
    changed = _write_if_changed(os.path.join(directory, unit), text)
    if changed:
        systemctl(run, "daemon-reload")
    if systemctl(run, "is-enabled", "--quiet", unit)[0] != 0:
        rc, out, err = systemctl(run, "enable", unit)
        if rc != 0:
            return changed, ("Instance '%s' will not start again after a reboot: "
                             "systemctl --user enable %s failed: %s"
                             % (instance_id, unit, (err or out).strip()))
        changed = True
    return changed, None


def disable(run, instance_id, remove=False):
    """Disable the unit, and remove it with remove=True. Returns changed."""
    unit = unit_name(instance_id)
    path = os.path.join(units_dir(), unit)
    if not os.path.exists(path):
        return False
    changed = False
    if systemctl(run, "is-enabled", "--quiet", unit)[0] == 0:
        systemctl(run, "disable", unit)
        changed = True
    if remove:
        os.remove(path)
        systemctl(run, "daemon-reload")
        changed = True
    return changed


def run_module():
    module = AnsibleModule(
        argument_spec=dict(
            state=dict(type="str", choices=["enabled", "disabled", "absent"],
                       default="enabled"),
            instance_id=dict(type="str", required=True),
            instance_path=dict(type="str"),
            compose_command=dict(type="str", default="docker compose"),
            inspect_command=dict(type="str", default="docker"),
            devmode=dict(type="bool", default=False),
        ),
        required_if=[("state", "enabled", ("instance_path",))],
        supports_check_mode=True,
    )
    params = module.params
    if not uses_units(params["inspect_command"]) or module.check_mode:
        module.exit_json(changed=False)

    def run(argv, env=None):
        return module.run_command(argv, environ_update=env or {})

    if params["state"] == "enabled":
        changed, warning = enable(run, params["instance_id"], params["instance_path"],
                                  params["compose_command"], params["devmode"])
        if warning:
            module.warn(warning)
    else:
        changed = disable(run, params["instance_id"], remove=params["state"] == "absent")
    module.exit_json(changed=changed, unit=unit_name(params["instance_id"]))


def main():
    run_module()


if __name__ == "__main__":
    main()
