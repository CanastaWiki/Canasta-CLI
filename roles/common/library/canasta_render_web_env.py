#!/usr/bin/python
# -*- coding: utf-8 -*-

"""Ansible module: render config/secret-keys-web to a Compose override layer.

Writes `docker-compose.web-env.yml`, which passes each listed key from .env
to the web service as `KEY=${KEY}`, or removes the file when the list is
empty or absent. Only key names are written; Compose interpolates the
values from .env.
"""

from __future__ import absolute_import, division, print_function
__metaclass__ = type

DOCUMENTATION = r"""
---
module: canasta_render_web_env
short_description: Render config/secret-keys-web to docker-compose.web-env.yml
description:
  - "Adds KEY=${KEY} to the web service environment for each listed key."
  - "Removes docker-compose.web-env.yml when no keys are listed."
options:
  instance_path:
    description: Path to the Canasta instance directory.
    type: str
    required: true
"""

import os
import re

from ansible.module_utils.basic import AnsibleModule

LIST_FILE = os.path.join("config", "secret-keys-web")
OVERLAY_FILE = "docker-compose.web-env.yml"

_HEADER = "# Generated by canasta from config/secret-keys-web — do not edit.\n"
_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def read_keys(instance_path):
    """Key names from the list file, in order, without duplicates."""
    path = os.path.join(instance_path, LIST_FILE)
    if not os.path.exists(path):
        return []
    keys = []
    with open(path) as handle:
        for line in handle:
            name = line.strip()
            if name and not name.startswith("#") and name not in keys:
                keys.append(name)
    return keys


def render(keys):
    """The overlay content for `keys`, or None when there are none."""
    if not keys:
        return None
    lines = [_HEADER, "services:\n", "  web:\n", "    environment:\n"]
    lines += ["    - %s=${%s}\n" % (k, k) for k in keys]
    return "".join(lines)


def write_or_remove(path, content, check_mode):
    """Write content, or remove the file when content is None. Returns True
    only when the file actually changed."""
    if content is None:
        if os.path.exists(path):
            if not check_mode:
                os.remove(path)
            return True
        return False
    existing = None
    if os.path.exists(path):
        with open(path) as handle:
            existing = handle.read()
    if existing == content:
        return False
    if not check_mode:
        with open(path, "w") as handle:
            handle.write(content)
    return True


def run_module():
    module = AnsibleModule(
        argument_spec=dict(
            instance_path=dict(type="str", required=True),
        ),
        supports_check_mode=True,
    )
    instance_path = module.params["instance_path"]
    keys = read_keys(instance_path)
    # Names are written into the YAML unquoted.
    bad = [k for k in keys if not _KEY_RE.match(k)]
    if bad:
        module.fail_json(
            msg="Refusing %s: %s %s not a valid environment variable name."
            % (LIST_FILE, ", ".join(bad), "is" if len(bad) == 1 else "are"))
    dest = os.path.join(instance_path, OVERLAY_FILE)
    changed = write_or_remove(dest, render(keys), module.check_mode)
    module.exit_json(changed=changed, keys=keys, path=dest)


def main():
    run_module()


if __name__ == "__main__":
    main()
