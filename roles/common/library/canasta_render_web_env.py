#!/usr/bin/python
# -*- coding: utf-8 -*-

"""Ansible module: render web environment keys to a Compose override layer.

Writes `docker-compose.web-env.yml`, which passes to the web service as
`KEY=${KEY}` each key listed in config/secret-keys-web (set with
`config set --secret --web`) or config/env-keys-web (set with
`config set --web`) that this host's .env defines, and each PHP-FPM pool
key .env sets; it removes the file when there
are none. Only key names are written; Compose interpolates the values from
.env. A key this host has no value for is left out: Compose would pass it as
an empty string and podman-compose as the literal `${KEY}`, and an unset pool
key has to keep the image default.
"""

from __future__ import absolute_import, division, print_function
__metaclass__ = type

DOCUMENTATION = r"""
---
module: canasta_render_web_env
short_description: Render web environment keys to docker-compose.web-env.yml
description:
  - "Adds KEY=${KEY} to the web service environment for each key listed in
    config/secret-keys-web or config/env-keys-web that .env defines, and each
    PHP-FPM pool key .env sets."
  - "Removes docker-compose.web-env.yml when there are no such keys."
options:
  instance_path:
    description: Path to the Canasta instance directory.
    type: str
    required: true
"""

import os
import re

from ansible.module_utils.basic import AnsibleModule

# Each list file, with the `config set` flags that add a key to it.
LIST_FILES = (
    (os.path.join("config", "secret-keys-web"), "--secret --web"),
    (os.path.join("config", "env-keys-web"), "--web"),
)
OVERLAY_FILE = "docker-compose.web-env.yml"

_HEADER = ("# Generated by canasta from .env, config/secret-keys-web and"
           " config/env-keys-web — do not edit.\n")
_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# PHP-FPM pool settings the image reads at startup. The edge sizes its limits
# from PM_MAX_CHILDREN in .env too.
POOL_KEYS = (
    "PHP_MEMORY_LIMIT",
    "PM_MAX_CHILDREN",
    "PM_START_SERVERS",
    "PM_MIN_SPARE_SERVERS",
    "PM_MAX_SPARE_SERVERS",
)


def read_keys(instance_path, list_file):
    """Key names from a list file, in order, without duplicates."""
    path = os.path.join(instance_path, list_file)
    if not os.path.exists(path):
        return []
    keys = []
    with open(path) as handle:
        for line in handle:
            name = line.strip()
            if name and not name.startswith("#") and name not in keys:
                keys.append(name)
    return keys


def read_env(instance_path):
    """Names defined in the instance .env, mapped to their raw values."""
    path = os.path.join(instance_path, ".env")
    values = {}
    if not os.path.exists(path):
        return values
    with open(path) as handle:
        for line in handle:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                name, value = line.split("=", 1)
                values[name.strip()] = value.strip().strip("'\"")
    return values


def render(keys):
    """The overlay content for `keys`, or None when there are none."""
    if not keys:
        return None
    lines = [_HEADER, "services:\n", "  web:\n", "    environment:\n"]
    lines += ["    - %s=${%s}\n" % (k, k) for k in keys]
    return "".join(lines)


def write_or_remove(path, content, check_mode):
    """Write content, or remove the file when content is None. Returns True
    only when the file actually changed."""
    if content is None:
        if os.path.exists(path):
            if not check_mode:
                os.remove(path)
            return True
        return False
    existing = None
    if os.path.exists(path):
        with open(path) as handle:
            existing = handle.read()
    if existing == content:
        return False
    if not check_mode:
        with open(path, "w") as handle:
            handle.write(content)
    return True


def run_module():
    module = AnsibleModule(
        argument_spec=dict(
            instance_path=dict(type="str", required=True),
        ),
        supports_check_mode=True,
    )
    instance_path = module.params["instance_path"]
    defined = read_env(instance_path)
    keys = []
    missing = []
    messages = []
    for list_file, flags in LIST_FILES:
        listed = read_keys(instance_path, list_file)
        # Names are written into the YAML unquoted.
        bad = [k for k in listed if not _KEY_RE.match(k)]
        if bad:
            module.fail_json(
                msg="Refusing %s: %s %s not a valid environment variable name."
                % (list_file, ", ".join(bad), "is" if len(bad) == 1 else "are"))
        absent = [k for k in listed if k not in defined and k not in missing]
        if absent:
            messages.append(
                "%s; set %s with 'canasta config set %s KEY=VALUE'"
                % (", ".join(absent), "it" if len(absent) == 1 else "them",
                   flags))
        missing += absent
        keys += [k for k in listed if k in defined and k not in keys]
    keys += [k for k in POOL_KEYS if defined.get(k) and k not in keys]
    if messages:
        module.warn(
            "Not passed to the web container because this host has no value "
            "for %s." % "; or ".join(messages))
    dest = os.path.join(instance_path, OVERLAY_FILE)
    changed = write_or_remove(dest, render(keys), module.check_mode)
    module.exit_json(changed=changed, keys=keys, missing=missing,
                     message="; or ".join(messages), path=dest)


def main():
    run_module()


if __name__ == "__main__":
    main()
